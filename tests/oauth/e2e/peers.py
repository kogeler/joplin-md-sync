class MockGitHubPeer:
    def __init__(self) -> None:
        self.github = MockGitHub()
        self.lock = threading.Lock()
        self.lookups = 0
        peer = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def do_GET(self):
                if self.path.startswith("/lookup/"):
                    peer.lookups += 1
                    data = json.dumps(
                        {"id": peer.github.user_id, "login": peer.github.login}
                    ).encode()
                    self.send_response(404 if self.path.endswith("/missing-fixture") else 200)
                    self.send_header("Content-Length", str(len(data)))
                    self.end_headers()
                    self.wfile.write(data)
                elif self.path.startswith("/authorize?"):
                    location = peer.github.authorize(
                        GITHUB_AUTHORIZE_URL + "?" + self.path.split("?", 1)[1]
                    )
                    self.send_response(302)
                    self.send_header("Location", location)
                    self.end_headers()
                else:
                    self.exchange()

            def do_POST(self):
                self.exchange()

            def exchange(self):
                endpoint = {"/token": GITHUB_TOKEN_URL, "/user": GITHUB_USER_URL}[self.path]
                body = self.rfile.read(int(self.headers.get("Content-Length", "0")))
                with peer.lock:
                    response = peer.github.request(
                        httpx2.Request(
                            self.command, endpoint, headers=dict(self.headers), content=body
                        )
                    )
                self.send_response(response.status_code)
                self.send_header("Content-Length", str(len(response.content)))
                for name, value in response.headers.items():
                    if name.lower() not in {"content-length", "connection"}:
                        self.send_header(name, value)
                self.end_headers()
                self.wfile.write(response.content)

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    def authorize(self, url: str) -> str:
        # A browser reaches the OAuth mock through actual HTTP, while preserving
        # the production authorize parameters generated by the real provider.
        with httpx2.Client(trust_env=False, follow_redirects=False) as client:
            response = client.get(self.url + "/authorize?" + urlsplit(url).query)
        assert response.status_code == 302
        return response.headers["location"]

    def close(self) -> None:
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=3)


def tls_material(directory: Path) -> tuple[Path, Path]:
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "localhost")])
    now = datetime.datetime.now(datetime.UTC)
    certificate = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(minutes=1))
        .not_valid_after(now + datetime.timedelta(days=1))
        .add_extension(
            x509.SubjectAlternativeName(
                [x509.DNSName("localhost"), x509.IPAddress(ipaddress.ip_address("127.0.0.1"))]
            ),
            critical=False,
        )
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .sign(key, hashes.SHA256())
    )
    cert, private = directory / "ca.pem", directory / "tls-key.pem"
    cert.write_bytes(certificate.public_bytes(serialization.Encoding.PEM))
    private.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    private.chmod(0o600)
    return cert, private


class HttpsProxy:
    def __init__(self, backend_port: int, directory: Path):
        self.backend_port = backend_port
        self.forwarded = 0
        self.forwarded_changed = threading.Condition()
        peer = self
        certificate, key = tls_material(directory)

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def forward(self):
                if urlsplit(self.path).path in {"/healthz", "/readyz"}:
                    self.send_response(404)
                    self.end_headers()
                    return
                body = self.rfile.read(int(self.headers.get("Content-Length", "0")))
                connection = socket.create_connection(("127.0.0.1", peer.backend_port), timeout=10)
                try:
                    # Buffer the complete upstream request, as the deployed
                    # reverse proxy does. Separate header/body writes can race
                    # an immediate authentication rejection and TCP close on
                    # Windows. Send exactly once; never replay a mutation.
                    head = (
                        f"{self.command} {self.path} HTTP/1.1\r\n"
                        + "".join(f"{name}: {value}\r\n" for name, value in self.headers.items())
                        + "\r\n"
                    )
                    connection.sendall(head.encode("latin-1") + body)
                    with peer.forwarded_changed:
                        peer.forwarded += 1
                        peer.forwarded_changed.notify_all()
                    result = http.client.HTTPResponse(connection)
                    result.begin()
                    content = result.read()
                    self.send_response(result.status)
                    for name, value in result.getheaders():
                        if name.lower() not in {
                            "content-length",
                            "transfer-encoding",
                            "connection",
                        }:
                            self.send_header(name, value)
                    self.send_header("Content-Length", str(len(content)))
                    self.end_headers()
                    self.wfile.write(content)
                finally:
                    connection.close()

            do_GET = forward
            do_POST = forward

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.minimum_version = ssl.TLSVersion.TLSv1_2
        context.load_cert_chain(certificate, key)
        self.server.socket = context.wrap_socket(self.server.socket, server_side=True)
        self.origin = f"https://127.0.0.1:{self.server.server_address[1]}"
        self.trust = ssl.create_default_context(cafile=str(certificate))
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    def wait_forwarded(self, count: int, timeout: float) -> bool:
        """Wait until ``count`` complete requests have reached the backend."""
        with self.forwarded_changed:
            return self.forwarded_changed.wait_for(lambda: self.forwarded >= count, timeout)

    def close(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=3)
